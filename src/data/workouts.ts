export function getPhaseFromWeek(week: number): 1 | 2 | 3 | 4 {
  if (week <= 5) return 1
  if (week <= 10) return 2
  if (week <= 15) return 3
  return 4
}

export function getPhaseName(phase: number): string {
  const names = { 1: 'Phase I', 2: 'Phase II', 3: 'Phase III', 4: 'Phase IV' }
  return names[phase as keyof typeof names] || 'Phase I'
}

export function getPhaseDescription(phase: number): string {
  const desc = {
    1: 'Mind-Muscle · Weeks 1–5',
    2: 'Strength · Weeks 6–10',
    3: 'Intensity · Weeks 11–15',
    4: 'Peak · Weeks 16–20',
  }
  return desc[phase as keyof typeof desc] || ''
}
